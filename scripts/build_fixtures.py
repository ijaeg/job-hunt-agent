"""Builds the cleaned demo/evaluation fixture set from the raw D-1 spike responses.

Reads the 40 raw listings in ``spikes/fixtures/details/`` (gitignored, D-3)
and the matching ``spikes/fixtures/search/`` responses, keeps only the
fields of :class:`JobSummary`/:class:`JobDetails`, cleans the free text with
:func:`job_hunt_agent.pii.clean_ad_text`, and adds three crafted fictional
listings for the demo scenarios (S5 prompt injection, a short teaser, a
temporary-agency listing). Writes the combined listing file,
``data/samples/fixtures/listings.json``, and a second, much smaller file,
``data/samples/fixtures/recorded_searches.json`` (query params + the real
recorded total + reference numbers only, no ad text) that lets
``ba_client.FixtureSource`` replay the 5 real D-1 search totals instead of
being capped at this fixture set's own size for every query (D-10 Option 4).
Both are read by ``ba_client.FixtureSource`` (FR-19 AC1).

**Referenznummer bug (D-1 regression, see spikes/NOTES.md § D-4):** the D-1
spike's own ad-hoc cleaning once matched a *reference number* with its
context-free phone regex, corrupting 3 of the ``referenznummer`` values
(e.g. ``19522-0068291613-S`` became ``19522-[TELEFON]-S``) wherever that
value appeared as a string - inside the JSON field itself, in both the
details file and the matching search-response item. This script therefore
takes the reference number from the details file's own ``referenznummer``
field whenever it is uncorrupted (no leftover ``[`` artifact), and only
falls back to the (lossy - the file name was generated by replacing every
``_`` and ``/`` with ``-``, D-10 follow-up 2) file-name stem for the 3
entries where the field itself is corrupted. Search-response items are
only used as a secondary source for ``distance_km`` (the one field details
responses do not carry), matched directly on the search item's own
``referenznummer`` - which still fails to match for those same 3 corrupted
search items, so their ``distance_km`` stays unset; every other field comes
straight from the details file, which is unaffected by that mismatch.

Usage (from the project root):
    uv run python scripts/build_fixtures.py

Related: FR-02 AC2, FR-04 AC2, FR-04 AC5, FR-19 AC1, FR-19 AC4, FR-22,
FR-23, D-1, D-3, D-8
"""

